import { PdfDocument } from './pdf';
import { buildXlsx, type SheetRow } from './xlsx';
import type { ExportTable, ReportExport } from './reportExport';

export type ExportFormat = 'Excel' | 'PDF';

/** The lines every export starts with: report name, period, filters and when it was generated. */
function headerRows(report: ReportExport): SheetRow[] {
  return [
  { cells: [report.name], bold: true },
  { cells: ['Period', report.period] },
  ...(report.filters.length === 0 ?
  [{ cells: ['Filters', 'None'] }] :
  report.filters.map((filter, index) => ({ cells: [index === 0 ? 'Filters' : '', filter] }))),
  { cells: ['Generated on', report.generatedOn] },
  { cells: ['Generated by', report.generatedBy] },
  { cells: [] }];

}

const tableRows = (table: ExportTable): SheetRow[] => [
{ cells: table.columns, bold: true },
...table.rows.map((row) => ({ cells: row }))];


/**
 * Two sheets: Summary (figures and each chart's totals) and the report's table with every row
 * behind it, each headed with the report details.
 */
export function excelFile(report: ReportExport): Blob {
  const summary: SheetRow[] = [
  ...headerRows(report),
  { cells: ['Figure', 'Value'], bold: true },
  ...report.figures.map((figure) => ({ cells: [figure.label, figure.value] })),
  ...report.charts.flatMap((chart) => [{ cells: [] }, { cells: [chart.title], bold: true }, ...tableRows(chart)])];

  return buildXlsx([
  { name: 'Summary', rows: summary },
  { name: report.table.title, rows: [...headerRows(report), ...tableRows(report.table)] }]
  );
}

export function pdfFile(report: ReportExport): Blob {
  const doc = new PdfDocument(`${report.name} · ${report.period} · Generated on ${report.generatedOn}`);
  doc.setRunningHeader(`${report.name} · ${report.period}`);
  doc.title(report.name);
  doc.field('Period', report.period);
  doc.field('Filters', report.filters.length === 0 ? 'None' : report.filters.join('; '));
  doc.field('Generated', `${report.generatedOn} by ${report.generatedBy}`);
  doc.gap(4);
  doc.table({
    title: 'Summary',
    columns: ['Figure', 'Value'],
    rows: report.figures.map((figure) => [figure.label, figure.value]),
    width: 460
  });
  report.charts.forEach((chart) => doc.table({ ...chart, width: chart.columns.length > 2 ? 460 : 300 }));
  doc.table(report.table);
  return doc.toBlob();
}

/** Saves the file through the browser's download. */
export function downloadFile(blob: Blob, fileName: string) {
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = fileName;
  document.body.appendChild(link);
  link.click();
  link.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
